<#
.SYNOPSIS
  Demo: run real Python code end-to-end through the business API.
  Flow: business API (port 8000) -> executor service (port 8101) -> Docker container.

.DESCRIPTION
  Shows: (1) submit Python code, (2) get execution result, (3) print stdout/stderr/exit code,
  (4) submit broken code and show the error feedback (syntax error + runtime error).

  Prerequisites:
    - Main API running:      ./scripts/start-server.ps1
    - Executor service:      ./scripts/start-executor-service.ps1  (needs ZD_EXECUTOR_TOKEN)
    - Docker Desktop running (otherwise the API honestly returns 503 with install hint;
      this demo also demonstrates that fail-closed behavior)

  Environment variables (or params):
    ZD_DEV_API_TOKEN  - dev mode token configured on the main API (required)
    ZD_EXECUTOR_TOKEN - token shared with the executor service (configured there)

  The script creates experiments/demo-python-run.json (experiment_id "py-web-demo")
  if missing. It is local demo content, safe to delete.

.PARAMETER BaseUrl
  Main API base URL. Default http://127.0.0.1:8000 (use 8100 if port 8000 is occupied).

.PARAMETER DevToken
  Dev mode token. Defaults to $env:ZD_DEV_API_TOKEN.
#>
param(
  [string]$BaseUrl = "http://127.0.0.1:8000",
  [string]$DevToken = $env:ZD_DEV_API_TOKEN
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($DevToken)) {
  Write-Host "[ERROR] ZD_DEV_API_TOKEN is not set. Start the main API with the same"
  Write-Host "        ZD_DEV_API_TOKEN value you pass here: $BaseUrl uses it as dev-mode gate."
  exit 1
}

$Headers = @{ "X-Dev-Token" = $DevToken }

function Invoke-Api {
  param([string]$Method, [string]$Uri, [object]$Body)
  # PS 5.1 compatible: HttpWebRequest gives readable error bodies on 4xx/5xx
  $req = [System.Net.HttpWebRequest]::Create($Uri)
  $req.Method = $Method
  $req.Timeout = 60000
  $req.Headers.Add("X-Dev-Token", $DevToken)
  if ($PSBoundParameters.ContainsKey("Body")) {
    $json = $Body | ConvertTo-Json -Depth 6
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
    $req.ContentType = "application/json; charset=utf-8"
    $req.ContentLength = $bytes.Length
    $stream = $req.GetRequestStream()
    $stream.Write($bytes, 0, $bytes.Length)
    $stream.Close()
  }
  try {
    $resp = $req.GetResponse()
  } catch [System.Net.WebException] {
    $resp = $_.Exception.Response
    if ($null -eq $resp) {
      Write-Host "[connection error] $($_.Exception.Message)"
      return $null
    }
  }
  $code = [int]$resp.StatusCode
  $reader = New-Object System.IO.StreamReader($resp.GetResponseStream(), [System.Text.Encoding]::UTF8)
  $text = $reader.ReadToEnd()
  $reader.Close()
  $resp.Close()
  if ($code -ge 400) {
    Write-Host "[HTTP $code] $text"
    return $null
  }
  if ($text) { return ($text | ConvertFrom-Json) }
  return $null
}

function Show-Result {
  param([object]$Result, [string]$Label)
  Write-Host ""
  Write-Host "=== $Label ==="
  if ($null -eq $Result) { return }
  Write-Host ("execution_id : " + $Result.execution_id)
  Write-Host ("status       : " + $Result.status)
  Write-Host ("exit_code    : " + $Result.exit_code)
  Write-Host ("duration_ms  : " + $Result.duration_ms)
  Write-Host ("stdout       : " + $Result.stdout)
  if ($Result.stderr) { Write-Host ("stderr       : " + $Result.stderr) }
}

# ---- Step 0: service status ----
Write-Host "BaseUrl: $BaseUrl"
$health = Invoke-Api -Method GET -Uri "$BaseUrl/api/v1/health"
if ($null -eq $health) { Write-Host "[ERROR] Main API is not reachable at $BaseUrl"; exit 1 }
Write-Host ("main api health: " + $health.status)

$status = Invoke-Api -Method GET -Uri "$BaseUrl/api/v1/executor/status"
if ($null -eq $status) {
  Write-Host "[WARN] Executor service unreachable or dev token mismatch."
  Write-Host "       If Docker is not installed this is expected: the run API stays fail-closed."
} else {
  Write-Host ("executor service   : " + $status.executor_service)
  Write-Host ("engine_available   : " + $status.engine_available)
  Write-Host ("image_digest_locked: " + $status.image_digest_locked)
  Write-Host ("docker_integration_tests: " + $status.docker_integration_tests)
  if (-not $status.docker_environment_ready) {
    Write-Host "[WARN] Docker environment is NOT ready. Runs below will fail-closed with 503 + install hint."
  }
}

