# ---- Step 2: submit working code ----
$goodCode = "total = sum(range(1, 11))`nprint('hello from sandbox')`nprint('sum 1..10 =', total)"
$good = Invoke-Api -Method POST -Uri "$BaseUrl/api/v1/experiments/py-web-demo/runs" `
  -Body @{ code = $goodCode; timeout_seconds = 10; task_id = "demo-good" }
Show-Result $good "RUN 1: working code"

# ---- Step 3: submit runtime-error code ----
$runtimeCode = "print('before')`nx = 1 / 0"
$runtime = Invoke-Api -Method POST -Uri "$BaseUrl/api/v1/experiments/py-web-demo/runs" `
  -Body @{ code = $runtimeCode; timeout_seconds = 10; task_id = "demo-runtime-error" }
Show-Result $runtime "RUN 2: runtime error (ZeroDivisionError)"

# ---- Step 4: submit syntax-error code ----
$syntaxCode = "def broken(:"
$syntax = Invoke-Api -Method POST -Uri "$BaseUrl/api/v1/experiments/py-web-demo/runs" `
  -Body @{ code = $syntaxCode; timeout_seconds = 10; task_id = "demo-syntax-error" }
